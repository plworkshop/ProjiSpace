// Archived languages use the same English fallback as translate for new features.
for (const dictionary of [german, spanish, french, portuguese, ukrainian, chinese, korean, japanese, hebrew]) {
  for (const [key, value] of Object.entries(english)) if (!(key in dictionary)) dictionary[key] = value;
}
export const dictionaries = { en: english, de: german, es: spanish, fr: french, pt: portuguese, uk: ukrainian, zh: chinese, ko: korean, ja: japanese, he: hebrew };

export function translate(message, language = "ru", values = {}) {
  const text = language === "ru" ? message : (dictionaries[language]?.[message] ?? english[message] ?? message);
  return text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
