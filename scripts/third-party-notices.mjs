import { readFile, readdir, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const noticeName = /^(?:(?:third[._-]party[._-])?licen[cs]es?|copying|notice|copyright(?:notice)?)(?:$|[._-])/i;
const licenseName = /^(?:licen[cs]e|copying)(?:$|[._-])/i;
const shippedBuildCode = {
  "node_modules/tailwindcss": "Generated CSS, including Tailwind preflight",
  "node_modules/vite": "Generated JavaScript modulepreload and import preload helpers",
};

function requireInside(directory, target) {
  const relative = path.relative(directory, target);
  if (!relative || relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error("A package or notice path escapes its expected directory.");
  }
}

async function readInside(directory, name) {
  const target = await realpath(path.join(directory, name));
  requireInside(directory, target);
  return readFile(target, "utf8");
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length && (args.length !== 1 || args[0] !== "--check")) {
    throw new Error("Usage: node scripts/third-party-notices.mjs [--check]");
  }
  const projectRoot = await realpath(root);
  const modulesDirectory = path.join(projectRoot, "node_modules");
  const modulesRoot = await realpath(modulesDirectory);
  requireInside(projectRoot, modulesRoot);
  const lock = JSON.parse(await readFile(path.join(projectRoot, "package-lock.json"), "utf8"));
  const entries = Object.entries(lock.packages).filter(([location, item]) =>
    location && (!item.dev || Object.hasOwn(shippedBuildCode, location)));
  for (const location of Object.keys(shippedBuildCode)) {
    if (!entries.some(([included]) => included === location)) {
      throw new Error(`Shipped build package is missing from package-lock.json: ${location}`);
    }
  }
  const productionCount = entries.filter(([, item]) => !item.dev).length;
  entries.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  const sections = [
    "ProjiSpace — third-party notices",
    "",
    "Generated by node scripts/third-party-notices.mjs from package-lock.json",
    "and the installed packages. Regenerate after changing dependencies.",
    `Includes ${productionCount} non-development lockfile entries from the runtime`,
    "dependency tree, including transitive, optional, and peer packages. Also",
    "includes Tailwind CSS/preflight and Vite JavaScript preload-helper notices",
    "because these build packages contribute code to the shipped application.",
    "Complete supplied license texts and their bundled notices follow, with",
    "line endings normalized to LF.",
    "",
    "Separately accompanying components",
    "",
    "Inter fonts: public/fonts/OFL.txt in the source; fonts/OFL.txt in the web build.",
    "Electron: LICENSE beside the executable in the desktop distribution.",
    "Chromium and its bundled components: LICENSES.chromium.html beside the",
    "executable in the desktop distribution.",
    "Whisper, ggml, and the speech model: desktop/voice/NOTICE.txt and LICENSE-*.txt",
    "in the source; resources/voice/NOTICE.txt and LICENSE-*.txt in the desktop",
    "distribution. The speech model is downloaded separately on user request.",
    "Ollama and assistant models are installed separately and retain their own",
    "licenses in their respective distributions.",
  ];
  for (const [location, item] of entries) {
    if (!location.startsWith("node_modules/") || location.includes("\\") ||
        location.split("/").some(part => !part || part === "." || part === "..") || item.link) {
      throw new Error(`Unsupported included package path: ${location}`);
    }
    const directory = path.resolve(projectRoot, location);
    requireInside(modulesDirectory, directory);
    const packageRoot = await realpath(directory);
    requireInside(modulesRoot, packageRoot);
    const metadata = JSON.parse(await readInside(packageRoot, "package.json"));
    const name = location.split("node_modules/").at(-1);
    if (metadata.name !== name || metadata.version !== item.version) {
      throw new Error(`Installed package does not match package-lock.json: ${location}`);
    }
    const files = (await readdir(packageRoot, { withFileTypes: true }))
      .filter(file => (file.isFile() || file.isSymbolicLink()) && noticeName.test(file.name))
      .map(file => file.name).sort();
    if (!files.some(file => licenseName.test(file))) {
      throw new Error(`No LICENSE or COPYING text found for ${name}@${item.version}`);
    }
    sections.push("", "=".repeat(72), `${name}@${item.version}`, `Package: ${location}`,
      `License identifier: ${item.license || "See supplied texts below"}`);
    if (Object.hasOwn(shippedBuildCode, location)) {
      sections.push(`Shipped contribution: ${shippedBuildCode[location]}`);
    }
    for (const file of files) {
      const text = (await readInside(packageRoot, file)).replace(/\r\n?/g, "\n");
      if (!text.trim()) throw new Error(`Empty notice text: ${name}/${file}`);
      sections.push("", `--- ${file} ---`, "", text.replace(/\n*$/, ""));
    }
  }
  const output = sections.join("\n") + "\n";
  const publicRoot = await realpath(path.join(projectRoot, "public"));
  requireInside(projectRoot, publicRoot);
  const destination = path.join(publicRoot, "THIRD_PARTY_NOTICES.txt");
  try { requireInside(publicRoot, await realpath(destination)); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  if (args[0] === "--check") {
    const current = await readFile(destination, "utf8").catch(error => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (current !== output) throw new Error("Third-party notices are missing or stale. Run node scripts/third-party-notices.mjs.");
    console.log(`Third-party notices are current (${entries.length} packages).`);
  } else {
    await writeFile(destination, output, "utf8");
    console.log(`Generated public/THIRD_PARTY_NOTICES.txt (${entries.length} packages).`);
  }
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
